"""Disposable QA appliance VM for the certified tester: `demo/demo qa create|reset|status|destroy`.

Wraps scripts/vmlab with its own VM name (qa-pinpoint-appliance), its own state
folder and the demo network (vboxnet1, appliance 10.77.1.1/27), so it never touches
the demo VMs. create and destroy print a plan and change nothing without --apply.
"""
import os
from pathlib import Path
import shutil
import subprocess
import sys

REPO=Path(__file__).resolve().parents[2]
sys.path.insert(0,str(REPO/'demo'))
from targets.catalog import load_catalog

VM='qa-pinpoint-appliance'
STATE=Path.home()/'.local/share/pinpoint-qa'
CONFIRMATION='destroy'
SSH_PORT='2251'


def target_ips():
    ips=[]
    for device in load_catalog().devices:
        if device.kind=='linux':
            ips.append(device.address)
    return ips


def config_text(ips):
    """vmlab settings only; no credentials. Ports differ from the demo appliance's."""
    return '\n'.join(['# Generated by demo/demo qa; safe to delete with the QA VM.',
                      'VMLAB_VM="%s"'%VM,
                      'VMLAB_SSH_PORT="%s"'%SSH_PORT,
                      'VMLAB_LAB_HOSTONLY="vboxnet1"',
                      'VMLAB_LAB_ADDRESS="10.77.1.1/27"',
                      'VMLAB_LAB_NETWORK="10.77.1.0/27"',
                      'VMLAB_TARGET_IPS="%s"'%','.join(ips),''])


def default_runner(argv,env=None):
    return subprocess.run(argv,env=env).returncode


def default_vm_exists(name):
    result=subprocess.run(['VBoxManage','showvminfo',name,'--machinereadable'],capture_output=True)
    return result.returncode==0


def vmlab(runner,state,*args):
    env=dict(os.environ,VMLAB_CONFIG=str(state/'vmlab.env'),VMLAB_STATE_DIR=str(state))
    return runner([str(REPO/'scripts'/'vmlab'),*args],env)


def main(argv,runner=default_runner,ask=input,vm_exists=default_vm_exists,state_dir=STATE,out=sys.stdout,err=sys.stderr):
    commands={'create','reset','status','destroy'}
    apply='--apply' in argv[1:]
    if not argv or argv[0] not in commands or any(a!='--apply' for a in argv[1:]) or len(argv)>2:
        print('usage: demo/demo qa create [--apply] | reset | status | destroy [--apply]',file=err)
        return 2
    command=argv[0]
    exists=vm_exists(VM)
    if command=='create':
        print('QA appliance plan (VM %s, host-only vboxnet1, appliance 10.77.1.1/27):'%VM,file=out)
        for step in ('iso: download the Ubuntu 22.04 ISO once','create: build the VM unattended',
                     'provision: install Ubuntu + Nagios and take the snapshot','fresh: install the current pushed branch and run the health check'):
            print('  '+step,file=out)
        if exists:
            print('The QA VM already exists; use demo/demo qa reset, or destroy it first.',file=err)
            return 1
        if not apply:
            print('Nothing was changed. Add --apply to build it (about 30 to 60 minutes).',file=out)
            return 0
        state_dir.mkdir(parents=True,exist_ok=True,mode=0o700)
        (state_dir/'vmlab.env').write_text(config_text(target_ips()))
        for step in ('iso','create','provision','fresh'):
            if vmlab(runner,state_dir,step):
                print('QA create stopped at "%s"; fix it and re-run the matching scripts/vmlab step.'%step,file=err)
                return 1
        print('QA appliance ready. Next: demo/demo setup --apply (containers), then scripts/vmlab setup-admin.',file=out)
        return 0
    if command=='destroy':
        print('Would remove:' if not apply else 'Removing:',file=out)
        print('  VM %s and its disk%s'%(VM,'' if exists else ' (not present)'),file=out)
        print('  QA state folder %s (QA keys and credentials)'%state_dir,file=out)
        if not apply:
            print('Nothing was changed. Add --apply and type "%s".'%CONFIRMATION,file=out)
            return 0
        if ask('Type "%s" to remove the QA VM and its state: '%CONFIRMATION)!=CONFIRMATION:
            print('Not confirmed; nothing was removed.',file=err)
            return 1
        if exists:
            runner(['VBoxManage','controlvm',VM,'poweroff'],None)
            if runner(['VBoxManage','unregistervm',VM,'--delete'],None):
                print('Could not remove the VM.',file=err)
                return 1
        if exists and state_dir.exists():
            shutil.rmtree(state_dir)
        print('Removed.',file=out)
        return 0
    if not exists:
        print('There is no QA VM; run demo/demo qa create --apply first.',file=err)
        return 1
    if command=='status':
        return vmlab(runner,state_dir,'status')
    return vmlab(runner,state_dir,'fresh')


if __name__=='__main__':
    raise SystemExit(main(sys.argv[1:]))
