def get_plugin_definition(plugin_name):
    """
    Return the PluginDefinition registered under plugin_name (case-
    insensitive). Raises PluginConfigurationError if there is none.
    """
    key = str(plugin_name).lower()
    definition = PLUGIN_DEFINITIONS.get(key) or INTERNAL_DEFINITIONS.get(key)
    if definition is None:
        raise PluginConfigurationError(f"Unknown plugin '{plugin_name}'.")
    return definition


def command_definition_name(plugin_name, variables):
    """
    The definition whose command a plugin's services use with these variables: "snmp" becomes
    "snmp_v3" once its protocol variable is 3, and "http" / "https" become their *_vhost definition
    once a virtual host is set. Every other plugin is its own, and so are v1 and v2c devices and web
    checks without a virtual host: they keep the command they always had.
    """
    if plugin_name == "snmp" and str(variables.get("protocol") or "") == "3":
        return SNMP_V3_DEFINITION.name
    if plugin_name in WEB_VHOST_DEFINITIONS and str(variables.get("virtual_host") or ""):
        return WEB_VHOST_DEFINITIONS[plugin_name].name
    return plugin_name


def command_definition_for(command, fallback):
    """The definition name behind a check_command string, so its `define command` gets written; fallback if it is a plain one."""
    name = str(command or "").split("!")[0]
    if name.startswith(COMMAND_NAME_PREFIX) and name[len(COMMAND_NAME_PREFIX):] in INTERNAL_DEFINITIONS:
        return name[len(COMMAND_NAME_PREFIX):]
    return fallback


def editable_variables(plugin_name):
    """
    The scalar variables an administrator may override per device for a registry plugin: its
    arguments, options and defaults (and, for SNMP, the v3 fields), without the values the system
    owns (a token, a metric path, one OID). Raises PluginConfigurationError for an unknown plugin.
    """
    definition = get_plugin_definition(plugin_name)
    names = {variable for _flag, variable in definition.arguments}
    names |= set(definition.options) | set(definition.defaults) | set(definition.extra_variables)
    if plugin_name == "snmp":
        names |= set(SNMP_V3_DEFINITION.options) | set(SNMP_V3_DEFINITION.defaults)
    return names - NON_EDITABLE_VARIABLES


# Values the system owns, or that exist once per service rather than per device.
NON_EDITABLE_VARIABLES = frozenset({"token", "metric_path", "oid"})


def find_plugin_by_name_or_alias(name):
    """
    Return the PluginDefinition whose name or alias matches name
    (case-insensitive), or None.
    """
    key = str(name or "").lower().strip()
    if key in PLUGIN_DEFINITIONS:
        return PLUGIN_DEFINITIONS[key]
    for definition in PLUGIN_DEFINITIONS.values():
        if key in definition.aliases:
            return definition
    return None


def resolve_plugin_name(service_name, transport):
    """
    Map a discovered service name (nmap's guess, after the configured
    overrides) to a plugin name. The service must match a plugin's name or
    alias AND that plugin must support the transport it was found on;
    anything else is monitored by the transport's generic port-check plugin.
    """
    definition = find_plugin_by_name_or_alias(service_name)
    if definition is not None and transport in definition.transports:
        return definition.name
    return GENERIC_PLUGIN_FOR_TRANSPORT[transport]


def plugin_for_definition(definition_name):
    """
    Return the Plugin Manager plugin (the executable name, e.g. "check_ssh")
    that checks a registry definition ("ssh"), or None for an unknown name.
    http and https share check_http. A definition is monitored only while this
    plugin is Enabled or Active in Plugin Manager.
    """
    definition = PLUGIN_DEFINITIONS.get(str(definition_name or "").lower().strip())
    return definition.check_plugin if definition else None


def service_options():
    """
    The service names and aliases the registry knows, for suggesting a service when pinning a
    port: [{"name": "ssh", "plugin": "check_ssh", "protocols": ["tcp"]}, ...] sorted by name.
    The generic port checks (tcp, udp) are left out because they are what every other name falls
    back to. Any other valid name is accepted too; it is checked by the generic TCP plugin (TCP)
    or skipped (UDP).
    """
    generic = set(GENERIC_PLUGIN_FOR_TRANSPORT.values())
    options = []
    for definition in PLUGIN_DEFINITIONS.values():
        if definition.name in generic:
            continue
        protocols = [transport.value.lower() for transport in definition.transports]
        for name in (definition.name, *definition.aliases):
            options.append({"name": name, "plugin": definition.check_plugin, "protocols": protocols})
    return sorted(options, key=lambda option: option["name"])


def service_driven_plugin_names():
    """
    The Plugin Manager plugins that check a discovered service, i.e. every
    check plugin some registry definition uses (check_ssh, check_http, ...).
    Only these can be enabled and disabled: enabling one attaches it to the
    discovered ports it can check. Any other plugin is "not service-driven".
    """
    return frozenset(definition.check_plugin for definition in PLUGIN_DEFINITIONS.values())


def is_service_driven(plugin_name):
    """True if a Plugin Manager plugin name (extension ignored) is in service_driven_plugin_names()."""
    return normalize_plugin_name(plugin_name) in service_driven_plugin_names()


def plugin_for_command(command_name):
    """
    Return the check plugin (e.g. "check_snmp") behind a Nagios command name
    reported by statusjson.cgi, or None if it is not one this registry
    generates. Arguments after "!" are ignored.
    """
    name = str(command_name or "").split("!")[0].strip()
    if not name.startswith(COMMAND_NAME_PREFIX):
        return None
    key = name[len(COMMAND_NAME_PREFIX):]
    definition = PLUGIN_DEFINITIONS.get(key) or INTERNAL_DEFINITIONS.get(key)
    return definition.check_plugin if definition else None


