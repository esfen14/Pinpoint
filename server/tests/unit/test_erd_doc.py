"""
tests/unit/test_erd_doc.py — Keeps docs/reference/ERD.md in step with the models.

The ERD is generated by server/scripts/generate_erd.py from the SQLAlchemy
metadata of system_models.py, plugin_models.py and history_models.py. These tests
fail when the committed file is stale, or when a table has no domain.

To refresh the file after a model change, from server/:

    python scripts/generate_erd.py
"""
import importlib.util
import os

SERVER_DIR = os.path.dirname(os.path.dirname(os.path.dirname(__file__)))
REPO_DIR = os.path.dirname(SERVER_DIR)
ERD_PATH = os.path.join(REPO_DIR, "docs", "reference", "ERD.md")
GENERATOR_PATH = os.path.join(SERVER_DIR, "scripts", "generate_erd.py")


def load_generator():
    """Import scripts/generate_erd.py by path (scripts/ is not a package)."""
    spec = importlib.util.spec_from_file_location("generate_erd", GENERATOR_PATH)
    module = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(module)
    return module


def test_committed_erd_matches_models():
    generator = load_generator()
    with open(ERD_PATH, encoding="utf-8") as handle:
        committed = handle.read()
    assert committed == generator.build_erd_markdown(), (
        "docs/reference/ERD.md is stale; run `python scripts/generate_erd.py` from server/"
    )


def test_every_table_has_exactly_one_domain():
    generator = load_generator()
    tables = generator.collect_tables()
    assigned = {}
    for domain_name, domain_tables in generator.DOMAINS:
        for table_name in domain_tables:
            assert table_name not in assigned, f"{table_name} is in two domains"
            assigned[table_name] = domain_name
    missing = []
    for table_name in tables:
        if table_name not in assigned:
            missing.append(table_name)
    assert not missing, f"add these tables to DOMAINS in generate_erd.py: {missing}"
    unknown = []
    for table_name in assigned:
        if table_name not in tables:
            unknown.append(table_name)
    assert not unknown, f"DOMAINS names tables that no longer exist: {unknown}"


def test_erd_has_overview_and_one_diagram_per_domain():
    generator = load_generator()
    text = generator.build_erd_markdown()
    assert text.count("```mermaid") == 1 + len(generator.DOMAINS)
    assert "## Overview" in text
    for domain_name, _ in generator.DOMAINS:
        assert f"## {domain_name}" in text


def test_overview_has_no_columns_and_domains_do():
    generator = load_generator()
    text = generator.build_erd_markdown()
    overview = text.split("## Overview", 1)[1].split("\n## ", 1)[0]
    assert "PK" not in overview
    assert " PK" in text
    assert " FK" in text
