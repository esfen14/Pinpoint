"""
Plugin registry for the Nagios configuration generated by Network Discovery.

Every monitored service is resolved from a PLUGIN NAME (snmp, ncpa, http, ...)
to a PluginDefinition — never from a port. A port is just one of the plugin's
variables: defaulted by the definition, replaced by the port the service was
actually discovered on, and overridable per host.

Resolution order
----------------
    discovered service name ──► plugin name   (name/alias match, else the
            │                                  generic "tcp" plugin; unmatched
            │                                  UDP ports are skipped)
            ▼
    PluginDefinition ──► transports, variables, checks, command layout
            │
            ▼
    variables = definition defaults
              < app config defaults   (e.g. SNMP_COMMUNITY_STRING, SNMP_OIDS)
              < discovery facts       (port found on, NCPA token, partitions)
              < host overrides        (NetworkDiscovery.Plugin_Variables)
            │
            ▼
    checks(variables) ──► one ServiceCheck per metric (SNMP OID, NCPA metric…)
            │
            ▼
    resolve_plugin_command() ──► "pinpoint_nd_snmp!161!public!1.3.6.1…!"

Each definition renders its own Nagios `define command` object named
pinpoint_nd_<plugin>, so generated configs never depend on which commands
happen to exist in the stock commands.cfg. The pinpoint_nd_ prefix keeps
them distinct from the pinpoint_<plugin> commands the retired manual Plugin
Manager path generated.

Adding a plugin — including one that produces many services — only means
adding a PluginDefinition to PLUGIN_DEFINITIONS. Neither the resolver nor
the config generator needs to change.

Security: every variable value ends up inside a Nagios object file and a
shell-executed command line. Values are single-quoted in the generated
command_line and any character that could escape that quoting, split
Nagios arguments (!), expand a macro ($) or start a cfg comment (;) is
rejected. Error messages name the offending variable, never its value, so
secrets such as the NCPA token are not leaked into logs.
"""
import re
from dataclasses import dataclass, field
from enum import Enum
from typing import Callable, Optional

COMMAND_NAME_PREFIX = "pinpoint_nd_"

# Script extensions a plugin file may carry (check_ncpa.py). Plugin Manager keeps the real
# filename; everything that compares a plugin name strips these first.
PLUGIN_SCRIPT_EXTENSIONS = (".py", ".pl", ".sh")


def normalize_plugin_name(name):
    """
    The plugin name without a script extension, lowercased and stripped: "check_ncpa.py" and
    "check_ncpa" both give "check_ncpa". Use it on BOTH sides of any comparison between a
    Plugin Manager name and a registry check_plugin, catalog key or command default. Stored
    names, Executable Path and generated commands keep the real filename.
    """
    key = str(name or "").strip().lower()
    for extension in PLUGIN_SCRIPT_EXTENSIONS:
        if key.endswith(extension):
            return key[:-len(extension)]
    return key

# Characters that could break out of a single-quoted shell argument, split
# Nagios' "!" argument list, expand a Nagios macro, or start a cfg comment.
FORBIDDEN_VALUE_CHARACTERS = frozenset("'\"`!$;\\\n\r\0")

# Characters Nagios refuses in object names (illegal_object_name_chars
# default), plus whitespace, which would make service names awkward to use.
ILLEGAL_NAME_CHARACTERS = re.compile(r"[`~!$%^&*|'\"<>?,()=\s]")

COMMAND_TEMPLATE = """define command {{
    command_name    {command_name}
    command_line    {command_line}
}}
"""


class Transport(Enum):
    TCP = "TCP"
    UDP = "UDP"


class PluginConfigurationError(ValueError):
    """
    Raised when a plugin cannot be resolved into a valid Nagios command —
    unknown plugin, missing required variable, unsafe value, or a transport
    the plugin does not support. Messages never contain variable values.
    """


@dataclass(frozen=True)
class ServiceCheck:
    """
    One Nagios service produced by a plugin. metric is None for plugins that
    produce a single service (e.g. ssh); otherwise it names the data point
    (e.g. "uptime" for an SNMP OID, "cpu" for an NCPA metric). variables are
    layered on top of the plugin's resolved variables for this service only.
    """
    metric: Optional[str]
    skip_reason: Optional[str] = None
    variables: dict = field(default_factory=dict)


def single_check(variables):
    """
    Default checks provider: the plugin produces exactly one service using
    the plugin-level variables unchanged.
    """
    return [ServiceCheck(metric=None)]


# IF-MIB columns the bandwidth monitoring reads: ifInOctets and ifOutOctets, indexed by ifIndex.
IF_IN_OCTETS_OID = "1.3.6.1.2.1.2.2.1.10"
IF_OUT_OCTETS_OID = "1.3.6.1.2.1.2.2.1.16"

# Most interfaces one device can have monitored; each one adds two Nagios services.
MAX_MONITORED_INTERFACES = 16
MAX_INTERFACE_INDEX = 2 ** 31 - 1


def interface_metrics(if_index):
    """
    Return (in_metric, out_metric), the SNMP metric names of the octet services of the interface
    with this ifIndex, e.g. ("if5_in_octets", "if5_out_octets") for the services
    "snmp-if5_in_octets-161-udp" and "snmp-if5_out_octets-161-udp".
    """
    return f"if{if_index}_in_octets", f"if{if_index}_out_octets"


def valid_interface_indexes(interfaces):
    """
    Return the ifIndex numbers in `interfaces` as a sorted list without duplicates, or raise
    PluginConfigurationError. Expects a list of integers from 1 to MAX_INTERFACE_INDEX, at most
    MAX_MONITORED_INTERFACES of them.
    """
    if not isinstance(interfaces, list):
        raise PluginConfigurationError("SNMP variable 'interfaces' must be a list.")
    indexes = set()
    for entry in interfaces:
        if isinstance(entry, bool) or not isinstance(entry, int) or not 1 <= entry <= MAX_INTERFACE_INDEX:
            raise PluginConfigurationError("Each SNMP interface must be an interface index (a whole number).")
        indexes.add(entry)
    if len(indexes) > MAX_MONITORED_INTERFACES:
        raise PluginConfigurationError(f"At most {MAX_MONITORED_INTERFACES} interfaces can be monitored on one device.")
    return sorted(indexes)


def snmp_checks(variables):
    """
    One service per configured OID. Expects variables["oids"] to be a list of
    {"metric": ..., "oid": ...} dicts; any other key in an entry (warning,
    critical, label, units) is passed through as a per-service variable.

    variables["interfaces"], when present, is a list of ifIndex numbers chosen for bandwidth
    monitoring (Device Inventory). Each adds an in and an out octet service after the OID
    services; see interface_metrics. With no interfaces the services are exactly the OID list.
    """
    oids = variables.get("oids") or []
    if not isinstance(oids, list):
        raise PluginConfigurationError("SNMP variable 'oids' must be a list.")

    checks = []
    for entry in oids:
        if not isinstance(entry, dict) or not entry.get("oid") or not entry.get("metric"):
            raise PluginConfigurationError("Each SNMP OID entry needs an 'oid' and a 'metric'.")

        per_service = dict(entry)
        metric = per_service.pop("metric")
        checks.append(ServiceCheck(metric=metric, variables=per_service))

    for if_index in valid_interface_indexes(variables.get("interfaces") or []):
        in_metric, out_metric = interface_metrics(if_index)
        checks.append(ServiceCheck(metric=in_metric, variables={"oid": f"{IF_IN_OCTETS_OID}.{if_index}"}))
        checks.append(ServiceCheck(metric=out_metric, variables={"oid": f"{IF_OUT_OCTETS_OID}.{if_index}"}))
    return checks


def ncpa_checks(variables):
    """
    One service per configured NCPA metric. Expects variables["metrics"] to be
    a list of {"metric": ..., "path": ...} dicts. A path containing
    "{partition}" expands to one service per entry in variables["partitions"]
    (discovered during NCPA installation); if no partitions are known, the
    entry's "fallback_path" is used as a single service instead. Confirmed
    unavailable paths carry a skip_reason; an unverified inventory defers the
    added defaults while preserving established checks.
    """
    metrics = variables.get("metrics") or []
    partitions = variables.get("partitions") or []
    if not isinstance(metrics, list) or not isinstance(partitions, list):
        raise PluginConfigurationError("NCPA variables 'metrics' and 'partitions' must be lists.")

    checks = []
    for entry in metrics:
        if not isinstance(entry, dict) or not entry.get("path") or not entry.get("metric"):
            raise PluginConfigurationError("Each NCPA metric entry needs a 'path' and a 'metric'.")

        per_service = dict(entry)
        metric = per_service.pop("metric")
        path = per_service.pop("path")
        fallback_path = per_service.pop("fallback_path", None)

        if "{partition}" not in path:
            checks.append(ServiceCheck(metric=metric, variables={**per_service, "metric_path": path}))
        elif partitions:
            for partition in partitions:
                # NCPA writes "/" as "|": "|" is the root mount, "|boot|efi" is /boot/efi.
                label = str(partition).strip("|").replace("|", "_") or "root"
                checks.append(ServiceCheck(
                    metric=f"{metric}_{label}",
                    variables={**per_service, "metric_path": path.replace("{partition}", str(partition))},
                ))
        elif fallback_path:
            checks.append(ServiceCheck(metric=metric, variables={**per_service, "metric_path": fallback_path}))
    available = variables.get("available_paths")
    unverified = variables.get("paths_unverified", False)
    if available is not None or unverified:
        # Inventory failure is unknown, not proof that established paths vanished.
        # Defer only the added defaults; a confirmed missing path skips any metric.
        from config import Config
        added_defaults = {(entry["metric"], entry["path"]) for entry in Config.NCPA_METRICS
                          if entry["metric"] in {"swap", "disk_read", "disk_write"}}
        verified = []
        for check in checks:
            path = check.variables["metric_path"]
            reason = None
            if unverified and (check.metric, path) in added_defaults:
                reason = f"NCPA metric {sanitize_name_part(check.metric)}: agent paths could not be verified; retry when the agent is reachable."
            elif available is not None and path not in available:
                reason = f"NCPA metric {sanitize_name_part(check.metric)}: the agent does not provide this path."
            verified.append(ServiceCheck(metric=check.metric, variables=check.variables, skip_reason=reason))
        checks = verified
    return checks


# SNMP versions check_snmp -P accepts, and the v3 fields it needs per security level (-L).
SNMP_VERSIONS = ("1", "2c", "3")
SNMP_SECURITY_LEVELS = ("noAuthNoPriv", "authNoPriv", "authPriv")
SNMP_AUTH_PROTOCOLS = ("MD5", "SHA")
SNMP_PRIV_PROTOCOLS = ("DES", "AES")
SNMP_USER_PATTERN = re.compile(r"^[A-Za-z0-9][A-Za-z0-9_.@-]{0,31}$")
SNMP_PASSWORD_LENGTH = (8, 64)
SNMP_V3_REQUIRED = {
    "noAuthNoPriv": ("v3_user",),
    "authNoPriv": ("v3_user", "auth_protocol", "auth_password"),
    "authPriv": ("v3_user", "auth_protocol", "auth_password", "priv_protocol", "priv_password"),
}
SNMP_V3_FIELDS = ("security_level", "v3_user", "auth_protocol", "auth_password", "priv_protocol", "priv_password")
